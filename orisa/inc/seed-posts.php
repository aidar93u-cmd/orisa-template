function orisa_seed_blog_classic($p) {
    $html = '<p>' . $p['lead'] . '</p>';
    foreach ($p['texts'] as $t) {
        $html .= $t;
    }
    if (!empty($p['cols'])) {
        foreach ($p['cols'] as $c) {
            $html .= '<h3>' . $c[0] . '</h3><p>' . $c[1] . '</p>';
        }
    }
    return $html;
}

function orisa_seed_blog_posts() {
    if (!isset($_GET['orisa_seed_blog']) || !current_user_can('manage_options')) {
        return;
    }
    if (!function_exists('acf_add_local_field_group')) {
        wp_die('Нужен плагин ACF Pro: группа «Блоки статьи» не зарегистрирована.');
    }
    $force = !empty($_GET['orisa_seed_force']);
    if (get_option('orisa_blog_seeded') && !$force) {
        wp_die('Блог уже заполнен. Повторно: ?orisa_seed_blog=1&orisa_seed_force=1');
    }
    require_once ABSPATH . 'wp-admin/includes/media.php';
    require_once ABSPATH . 'wp-admin/includes/file.php';
    require_once ABSPATH . 'wp-admin/includes/image.php';

    $cats = ['bankrotstvo' => 'Банкротство', 'dolgi' => 'Долги', 'kredity' => 'Кредиты', 'ipoteka' => 'Ипотека'];
    $cat_ids = [];
    foreach ($cats as $slug => $name) {
        $t = term_exists($slug, 'category');
        if (!$t) {
            $t = wp_insert_term($name, 'category', ['slug' => $slug]);
        }
        if (!is_wp_error($t) && isset($t['term_id'])) {
            $cat_ids[$slug] = (int) $t['term_id'];
        }
    }

    $created = [];
    $skipped = [];
    foreach (orisa_seed_blog_data() as $p) {
        if (get_page_by_path($p['slug'], OBJECT, 'post')) {
            $skipped[] = $p['slug'];
            continue;
        }
        $post_id = wp_insert_post([
            'post_title'    => $p['title'],
            'post_name'     => $p['slug'],
            'post_content'  => orisa_seed_blog_classic($p),
            'post_excerpt'  => $p['excerpt'],
            'post_status'   => 'publish',
            'post_type'     => 'post',
            'post_author'   => get_current_user_id(),
            'post_date'     => $p['date'],
            'post_category' => isset($cat_ids[$p['cat']]) ? [$cat_ids[$p['cat']]] : [],
            'tags_input'    => $p['tags'],
        ], true);
        if (is_wp_error($post_id) || !$post_id) {
            $skipped[] = $p['slug'] . ' (ошибка создания)';
            continue;
        }
        $src = ORISA_DIR . '/assets/imgs/blog/' . $p['img'];
        if (is_readable($src)) {
            $tmp = tempnam(sys_get_temp_dir(), 'orisa') . '.jpg';
            if (@copy($src, $tmp)) {
                $att = media_handle_sideload(['name' => $p['img'], 'tmp_name' => $tmp], $post_id);
                if (!is_wp_error($att)) {
                    set_post_thumbnail($post_id, $att);
                }
                @unlink($tmp);
            }
        }
        $rows = [];
        $rows[] = ['acf_fc_layout' => 'post_lead', 'field_orisa_post_lead_text' => $p['lead']];
        foreach ($p['texts'] as $t) {
            $rows[] = ['acf_fc_layout' => 'post_text', 'field_orisa_post_text_body' => $t];
        }
        if (!empty($p['cols'])) {
            $crows = [];
            foreach ($p['cols'] as $c) {
                $crows[] = ['field_orisa_post_col_heading' => $c[0], 'field_orisa_post_col_text' => $c[1]];
            }
            $rows[] = ['acf_fc_layout' => 'post_columns', 'field_orisa_post_columns_rows' => $crows];
        }
        update_field('field_orisa_post_blocks', $rows, $post_id);
        $created[] = $p['title'];
    }
    update_option('orisa_blog_seeded', 1);
    $blog_url = get_post_type_archive_link('post');
    wp_die(
        'Готово. Создано статей: ' . count($created) . ', пропущено: ' . count($skipped)
        . ($skipped ? ' (' . implode(', ', $skipped) . ')' : '')
        . '. <a href="' . esc_url($blog_url ? $blog_url : home_url('/')) . '">Открыть блог</a>'
    );
}

/**
 * Замена миниатюр сидированных статей: файлы в assets/imgs/blog/ уже
 * обновлены (имена те же), старые вложения удаляются вместе с файлами.
 */
function orisa_seed_blog_images() {
    if (!isset($_GET['orisa_seed_images']) || !current_user_can('manage_options')) {
        return;
    }
    require_once ABSPATH . 'wp-admin/includes/media.php';
    require_once ABSPATH . 'wp-admin/includes/file.php';
    require_once ABSPATH . 'wp-admin/includes/image.php';
    $done = [];
    $missed = [];
    foreach (orisa_seed_blog_data() as $p) {
        $post = get_page_by_path($p['slug'], OBJECT, 'post');
        if (!$post) {
            $missed[] = $p['slug'] . ' (нет поста)';
            continue;
        }
        $src = ORISA_DIR . '/assets/imgs/blog/' . $p['img'];
        if (!is_readable($src)) {
            $missed[] = $p['slug'] . ' (нет файла)';
            continue;
        }
        $tmp = tempnam(sys_get_temp_dir(), 'orisa') . '.jpg';
        if (!@copy($src, $tmp)) {
            $missed[] = $p['slug'] . ' (копия)';
            continue;
        }
        $att = media_handle_sideload(['name' => $p['img'], 'tmp_name' => $tmp], $post->ID);
        @unlink($tmp);
        if (is_wp_error($att) || !$att) {
            $missed[] = $p['slug'] . ' (загрузка)';
            continue;
        }
        $old = get_post_thumbnail_id($post->ID);
        set_post_thumbnail($post->ID, $att);
        if ($old && (int) $old !== (int) $att) {
            wp_delete_attachment((int) $old, true);
        }
        $done[] = $p['slug'];
    }
    wp_die(
        'Миниатюры заменены: ' . count($done) . ', пропущено: ' . count($missed)
        . ($missed ? ' (' . implode(', ', $missed) . ')' : '')
    );
}
